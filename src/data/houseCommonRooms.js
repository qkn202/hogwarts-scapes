/**
 * Dynamic Hogwarts House Common Rooms for Chapter 1 (`id: 0`, `homescapes`)
 * Adapts Chapter 1's 2.5D backdrop, Head-of-House story, cutscene, and all 9 renovation spots
 * to the player's (or visited friend's) Hogwarts House (`gryffindor`, `slytherin`, `ravenclaw`, `hufflepuff`)
 * while keeping identical task IDs (`hb_floor`..`hb_hearth`) for 100% save & online sync compatibility!
 */

const VALID_HOUSES = new Set(['gryffindor', 'slytherin', 'ravenclaw', 'hufflepuff']);

const st = (name, primary, secondary, accent, extra = {}) => ({
  name,
  primary,
  secondary,
  accent,
  ...extra,
});

const spot = (id, slot, icon, title, desc, styles, afterDialogue) => ({
  id,
  slot,
  icon,
  title,
  desc,
  styles,
  afterDialogue,
});

export function normalizeHogwartsHouse(rawHouse) {
  const clean = String(rawHouse || '').trim().toLowerCase();
  return VALID_HOUSES.has(clean) ? clean : 'gryffindor';
}

export function getHouseCommonSceneKey(rawHouse) {
  const h = normalizeHogwartsHouse(rawHouse);
  if (h === 'slytherin') return 'home_common_slytherin';
  if (h === 'ravenclaw') return 'home_common_ravenclaw';
  if (h === 'hufflepuff') return 'home_common_hufflepuff';
  return 'home_room_0';
}

