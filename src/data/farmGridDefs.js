export function getBuildingDef(type) {
  return FARM_BUILDINGS.find((b) => b.type === type) || null;
}

export function getParcelForCell(col, row) {
  return (
    FARM_PARCELS.find((p) => col >= p.c0 && col <= p.c1 && row >= p.r0 && row <= p.r1) || null
  );
}
